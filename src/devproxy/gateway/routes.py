"""Route table: data model, persistence, and Caddyfile rendering.

Rendering is a pure, deterministic function -- the same table always produces
byte-for-byte identical text.
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass
from dataclasses import field
from pathlib import Path

TABLE_VERSION = 1
RENDER_HEADER = "# Generated by devproxy -- do not edit by hand\n"


class RouteTableError(RuntimeError):
    """The route table file is corrupt or invalid."""


# Site addresses and upstreams are both spliced into Caddyfile text -- only a
# strict whitelist is allowed, and metacharacters such as braces/newlines/
# quotes are always rejected (not "escape and allow": Caddyfile has no
# reliable general escaping, so the only correct fix is to keep them out)
HOSTNAME_RE = re.compile(r"\A[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)*\Z")
HOSTPORT_RE = re.compile(r"\A[a-z0-9.-]+:\d{1,5}\Z")
MAX_HOSTNAME_LEN = 253


@dataclass
class Route:
    """One route = one exact site block."""

    name: str
    domain: str
    port: int
    mode: str  # "up" | "expose"
    upstream: str
    command: list[str] | None = None
    pid: int | None = None
    # Process start time of the pid (/proc stat field 22 / ps lstart) -- pids
    # are reused by the OS, so down uses it to confirm it is still killing
    # the original process. None = cannot verify
    proc_start: str | None = None
    created_at: str = ""
    # Declaration source: the **absolute path** of the project-level config
    # file (devproxy.toml). None = a route created manually with
    # `devproxy up` / `devproxy expose` -- `devproxy up --prune` never touches
    # them (processes the user started should not be removed by a file).
    source: str | None = None

    def to_dict(self) -> dict:
        d = {
            "name": self.name,
            "domain": self.domain,
            "port": self.port,
            "mode": self.mode,
            "upstream": self.upstream,
        }
        if self.command is not None:
            d["command"] = self.command
        if self.pid is not None:
            d["pid"] = self.pid
        if self.proc_start is not None:
            d["proc_start"] = self.proc_start
        if self.created_at:
            d["created_at"] = self.created_at
        if self.source is not None:
            d["source"] = self.source
        return d

    @classmethod
    def from_dict(cls, d: dict) -> Route:
        return cls(
            name=d["name"],
            domain=d["domain"],
            port=int(d["port"]),
            mode=d["mode"],
            upstream=d["upstream"],
            command=list(d["command"]) if d.get("command") is not None else None,
            pid=int(d["pid"]) if d.get("pid") is not None else None,
            proc_start=d.get("proc_start"),
            created_at=d.get("created_at", ""),
            source=d.get("source"),
        )


@dataclass
class RouteTable:
    version: int = TABLE_VERSION
    domain_suffix: str = "test"
    routes: list[Route] = field(default_factory=list)

    def get(self, name: str) -> Route | None:
        return next((r for r in self.routes if r.name == name), None)

    def upsert(self, route: Route) -> None:
        """Replace in place when the name matches."""
        for i, r in enumerate(self.routes):
            if r.name == route.name:
                self.routes[i] = route
                return
        self.routes.append(route)

    def remove(self, name: str) -> bool:
        before = len(self.routes)
        self.routes = [r for r in self.routes if r.name != name]
        return len(self.routes) < before

    def to_dict(self) -> dict:
        return {
            "version": self.version,
            "domain_suffix": self.domain_suffix,
            "routes": [r.to_dict() for r in self.routes],
        }

    @classmethod
    def from_dict(cls, d: dict) -> RouteTable:
        return cls(
            version=int(d.get("version", TABLE_VERSION)),
            domain_suffix=d.get("domain_suffix", "test"),
            routes=[Route.from_dict(r) for r in d.get("routes", [])],
        )


def atomic_write(path: Path, content: str) -> None:
    """Write a temp file first, then os.replace -- avoids reading partial
    content.

    The temp file name includes the pid: two writers never collide on the
    same temp file (a collision means overwriting each other's intermediate
    output, possibly mixing the written content). fsync before finishing --
    otherwise after a power loss os.replace may land on content that never
    reached the disk.

    Always remove our own temp file, whether we succeed or fail.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f"{path.name}.{os.getpid()}.tmp")
    try:
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(content)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)


def load_table(path: Path) -> RouteTable:
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        # Do not pre-check with exists(): _restore may delete the file between
        # the check and the read, and read_text would raise FileNotFoundError
        # (not a parse error) all the way to the CLI.
        return RouteTable()
    try:
        return RouteTable.from_dict(json.loads(text))
    except (json.JSONDecodeError, KeyError, ValueError, TypeError, AttributeError) as e:
        # routes.json is the tool's own state file, but manual edits / version
        # changes / partial writes are all realistic -- it must map to a
        # domain error so a raw KeyError never reaches the terminal
        raise RouteTableError(f"route table corrupt: {path} -- {e}") from e


def save_table(path: Path, table: RouteTable) -> None:
    atomic_write(path, json.dumps(table.to_dict(), ensure_ascii=False, indent=2) + "\n")


def check_renderable(route: Route) -> None:
    """Last gate before rendering: domain must be a hostname, upstream
    host:port.

    routes.json is the "truth", but the truth may have been edited by hand --
    the renderer must not pour arbitrary text straight into the Caddyfile
    configuration language.
    """
    domain = route.domain
    if (
        not isinstance(domain, str)
        or len(domain) > MAX_HOSTNAME_LEN
        or not HOSTNAME_RE.match(domain)
    ):
        raise RouteTableError(
            f"route {route.name!r} has invalid domain {domain!r} "
            "(only lowercase letters, digits, hyphens, and dots are allowed)"
        )
    upstream = route.upstream
    if not isinstance(upstream, str) or not HOSTPORT_RE.match(upstream):
        raise RouteTableError(
            f"route {route.name!r} upstream {upstream!r} must look like host:port"
        )
    if not 1 <= int(upstream.rpartition(":")[2]) <= 65535:
        raise RouteTableError(
            f"route {route.name!r} upstream {upstream!r} port is outside the 1-65535 range"
        )


DEFAULT_HTTPS_PORT = 443


def render_caddyfile(table: RouteTable, https_port: int = DEFAULT_HTTPS_PORT) -> str:
    """Render as a Caddyfile fragment: one route = one exact site block.

    Wildcard blocks and on-demand are deliberately avoided -- exact blocks
    mean unregistered domains cannot obtain a certificate.

    header_up adds X-Forwarded-Port: Caddy does **not** send this header by
    default, so the app cannot see the port the client actually connected to
    and falls back to its own listening port -- when ports are allocated
    dynamically (changing on every sync), the absolute URLs the app builds
    (e.g. SSO redirect_uri) carry a stale port. Hard-code the configured
    value: requests visible to the app can only come from https_port
    (http_port requests are automatically redirected to https by Caddy).
    """
    for route in table.routes:
        check_renderable(route)
    blocks = [
        f"{r.domain} {{\n\ttls internal\n\treverse_proxy {r.upstream} {{"
        f"\n\t\theader_up X-Forwarded-Port {https_port}\n\t}}\n}}"
        for r in table.routes
    ]
    if not blocks:
        return RENDER_HEADER
    return RENDER_HEADER + "\n" + "\n\n".join(blocks) + "\n"
