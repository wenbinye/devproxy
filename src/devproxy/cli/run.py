"""devproxy run -- supervise Caddy in the foreground.

The command itself only does three things: precondition checks, a pre-start
validation, and handing the exit code to typer. Starting the process and handling
signals live in `gateway.foreground` (selftest already starts Caddy there, so the
precedent exists).

Mutually exclusive with `setup`: the background service that setup installs holds
80/443, so a foreground instance cannot bind -- that is an unmet precondition
(exit 3) and the message carries this platform's stop command.
"""

from __future__ import annotations

from pathlib import Path

import typer

from devproxy.cli import _shared as s
from devproxy.cli import app
from devproxy.cli._shared import EXIT_FAIL
from devproxy.cli._shared import EXIT_PRECONDITION
from devproxy.cli._shared import EXIT_USAGE
from devproxy.core.config import Config
from devproxy.core.paths import Paths

# The command that stops the live caddy service, per platform -- the hint must hand the
# user something they can run as-is. Keys are platform.name ("linux" in linux.py,
# "mac" in macos.py); anything else (fake only appears in tests) gets the generic hint.
_STOP_COMMAND = {
    "linux": "systemctl --user stop caddy",
    "mac": "launchctl bootout system/com.devproxy.caddy",
}
_GENERIC_STOP_HINT = "stop the running caddy service first"


def _resolve_caddyfile(paths: Paths, explicit: Path) -> Path:
    """Decide which Caddyfile to load.

    An explicit --config wins (whether or not the main Caddyfile exists); only without
    it do we use the main Caddyfile -- that one must have been generated by setup, so
    its absence is an unmet precondition (3). An explicit path that does not exist is a
    usage error (2), matching how sync --file behaves.
    """
    if explicit is None:
        if not paths.caddyfile.exists():
            s.fail(
                f"main Caddyfile not found: {paths.caddyfile}; run devproxy setup first",
                EXIT_PRECONDITION,
            )
        return paths.caddyfile
    if not explicit.exists():
        s.fail(f"the file given to --config does not exist: {explicit}", EXIT_USAGE)
    return explicit


def _require_caddy_binary(config: Config) -> None:
    binary = config.caddy_bin_path
    if not binary.exists():
        s.fail(
            f"caddy binary not found: {binary}; run devproxy setup first",
            EXIT_PRECONDITION,
        )


def _require_no_active_service(paths: Paths, caddyfile: Path) -> None:
    """A live caddy service means 80/443 are taken, so a foreground instance cannot bind.

    **Only for the main Caddyfile**: that is the config the service unit loads, so both
    would fight over the same ports. When --config points somewhere else it usually uses
    a different set of ports (debugging and isolated instances exist for exactly that),
    so do not block -- if ports do collide, let Caddy report "address already in use",
    which is more accurate than any guess made here.
    """
    if caddyfile != paths.caddyfile:
        return
    platform = s._platform()
    if not platform.service_active("caddy"):
        return
    stop = _STOP_COMMAND.get(getattr(platform, "name", ""))
    if stop:
        # Command goes first: Rich wraps at 80 columns, and a command broken across lines
        # cannot be copied
        s.fail(
            f"run {stop} first (the caddy service is still running and holds 80/443)",
            EXIT_PRECONDITION,
        )
    s.fail(
        f"the caddy service is still running and holds 80/443: {_GENERIC_STOP_HINT}",
        EXIT_PRECONDITION,
    )


@app.command()
def run(
    config_path: Path = typer.Option(
        None, "--config", help="Caddyfile to load (the main Caddyfile by default)"
    ),
) -> None:
    """Supervise Caddy in the foreground (installs no service, keeps no state; Ctrl-C exits)."""
    paths, config, _, _ = s.build_context()
    caddyfile = _resolve_caddyfile(paths, config_path)
    _require_caddy_binary(config)
    _require_no_active_service(paths, caddyfile)

    # Validate before starting: a broken config should be reported here, not guessed at
    # after Caddy refuses to come up
    caddy = s.CaddyConfig(
        caddy_bin=config.caddy_bin_path,
        caddyfile=caddyfile,
        admin_addr=config.admin_addr,
    )
    ok, detail = caddy.validate(caddyfile)
    if not ok:
        s.fail(f"Caddy config validation failed: {detail}", EXIT_FAIL)

    from devproxy.gateway.foreground import run_foreground

    # Status messages go to stderr: stdout is the direct channel for Caddy's log, so do
    # not mix them
    s.err_console.print(
        f"devproxy: running caddy in the foreground (config {caddyfile}), Ctrl-C to exit"
    )
    raise typer.Exit(run_foreground(config.caddy_bin_path, caddyfile))
