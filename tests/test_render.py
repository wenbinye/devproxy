def test_atomic_write_leaves_no_tmp_file(tmp_path):
    p = tmp_path / "x.txt"
    atomic_write(p, "hello")
    assert p.read_text() == "hello"
    assert list(tmp_path.iterdir()) == [p]


def test_atomic_write_uses_unique_temp_name(tmp_path):
    """Temp file names must be unique -- otherwise two writers collide on the same intermediate artifact."""
    p = tmp_path / "x.txt"
    # Do not overwrite a temp file left behind by another process (different pid).
    foreign = tmp_path / "x.txt.424242.tmp"
    foreign.write_text("someone else's temp file", encoding="utf-8")
    atomic_write(p, "hello")
    assert p.read_text() == "hello"
    assert foreign.read_text(encoding="utf-8") == "someone else's temp file"


def test_atomic_write_fsyncs_before_replace(tmp_path, monkeypatch):
    """Must fsync before writing to disk -- otherwise after a power loss replace may point at content that never reached the disk."""
    calls = []
    real_fsync = os.fsync

    def spy(fd):
        calls.append(fd)
        return real_fsync(fd)

    monkeypatch.setattr(os, "fsync", spy)
    atomic_write(tmp_path / "x.txt", "hello")
    assert calls, "must fsync after writing the temp file"


def test_atomic_write_cleans_temp_on_failure(tmp_path, monkeypatch):
    """A failed write must not leave a temp file behind."""

    def boom(*a, **k):
        raise OSError("disk is full")

    monkeypatch.setattr(os, "replace", boom)
    with pytest.raises(OSError):
        atomic_write(tmp_path / "x.txt", "hello")
    assert list(tmp_path.iterdir()) == []


